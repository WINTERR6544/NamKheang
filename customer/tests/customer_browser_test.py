def check(condition, label):
    if not condition: raise AssertionError(label)
    results.append(label)
    print("PASS", label, flush=True)
def opened(browser, config=None, width=1440, height=1024):
    context = browser.new_context(viewport={"width":width,"height":height}, timezone_id="Asia/Bangkok")
    context.add_init_script("window.__fixtureConfig="+json.dumps(config or {}, ensure_ascii=False))
    context.add_init_script(path=str(root/"tests/customer_mock.js"))
    context.route("**/supabase.js", lambda route: route.fulfill(status=200, body="/* mocked only in tests */", content_type="application/javascript"))
    context.route("https://neotkiugfgktrjyzrbji.supabase.co/**", lambda route: route.abort())
    page=context.new_page()
    page.on("pageerror", lambda error: errors.append(str(error)))
    return context,page
def go(page, path):
    page.goto(base+"/"+path, wait_until="networkidle")
    page.wait_for_function("!document.querySelector('.loading')", timeout=10000)
def accept(page):
    page.locator("dialog [data-save]").click()
def call(page, name):
    return page.evaluate("(name)=>window.__calls.filter(c=>c.rpc===name).at(-1)", name)

